"""
Session 8 Data Integrity Validation Script.
Validates:
1. Database Integrity: All identities come from real MySQL `actors.full_name`.
2. Storage Integrity: All face images come from actual CAMP storage (`storage/app/public/actor-images/`).
3. Embeddings Integrity: All embeddings generated by YOLO + FaceNet into 128-D .npy files.
4. Orphan Free: Zero stale actors or orphaned files in reference directory or manifest.
5. Live Recognition Runtime on port 8002:
   - Real CAMP image of Bayu Eko Moektito -> Known ('Bayu Eko Moektito'), distance <= 0.65.
   - Non-registered face (lena.jpg) -> Unknown ('Unknown'), distance > 0.65.
"""

import sys
import json
import urllib.request
from pathlib import Path
import numpy as np

BASE_DIR = Path(__file__).resolve().parent.parent

# 1. Health check
print("[1] Checking Microservice Health on port 8002...")
req = urllib.request.Request("http://127.0.0.1:8002/health")
with urllib.request.urlopen(req) as resp:
    health = json.loads(resp.read().decode("utf-8"))
print(f"    Health Status: {health.get('status')}")
print(f"    Actors in Memory: {health.get('actors_loaded')} -> {health.get('actors_list')}")
print(f"    Distance Threshold: {health.get('distance_threshold')}")
assert health.get("status") == "ready"
assert health.get("distance_threshold") == 0.65
assert health.get("actors_list") == ["bayu_eko_moektito"]

# 2. Check manifest on disk
print("\n[2] Checking Reference Manifest on disk...")
manifest_path = BASE_DIR / "python" / "embeddings" / "manifest.json"
assert manifest_path.exists(), "manifest.json does not exist"
with open(manifest_path, "r", encoding="utf-8") as f:
    manifest = json.load(f)
actors_manifest = manifest.get("actors", {})
print(f"    Actors in Manifest: {list(actors_manifest.keys())}")
assert list(actors_manifest.keys()) == ["bayu_eko_moektito"]
bayu_entry = actors_manifest["bayu_eko_moektito"]
print(f"    Full Name from DB: '{bayu_entry.get('full_name')}'")
print(f"    Active Reference Files ({len(bayu_entry.get('files', []))} files): {bayu_entry.get('files')}")
assert bayu_entry.get("full_name") == "Bayu Eko Moektito"
assert len(bayu_entry.get("files", [])) == 10

# 3. Test Live Recognition with Real CAMP Image (Bayu Eko Moektito)
print("\n[3] Testing Live Recognition with Real CAMP Image...")
camp_img_path = BASE_DIR / "storage" / "app" / "public" / "actor-images" / "1-bayu-skak" / "bayu-skak-01.jpg"
assert camp_img_path.exists(), f"Image not found: {camp_img_path}"
with open(camp_img_path, "rb") as f:
    img_bytes = f.read()

req = urllib.request.Request("http://127.0.0.1:8002/detect", data=img_bytes, headers={"Content-Type": "image/jpeg"}, method="POST")
with urllib.request.urlopen(req) as resp:
    det_res = json.loads(resp.read().decode("utf-8"))

faces = det_res.get("faces", [])
print(f"    Detected Faces: {len(faces)}")
assert len(faces) > 0, "No face detected in real CAMP image"
f0 = faces[0]
print(f"    Face #1 -> Actor: '{f0.get('actor')}' | Status: '{f0.get('status')}' | Distance: {f0.get('distance')}")
assert f0.get("status") == "known", f"Expected 'known', got {f0.get('status')}"
assert f0.get("actor") == "Bayu Eko Moektito", f"Expected 'Bayu Eko Moektito', got {f0.get('actor')}"
assert f0.get("distance") <= 0.65, f"Expected distance <= 0.65, got {f0.get('distance')}"
print("    [PASS] Real actor recognized accurately with exact MySQL full_name and distance <= 0.65!")

# 4. Test Live Recognition with Non-registered Face (lena.jpg)
print("\n[4] Testing Live Recognition with Unregistered Face (lena.jpg)...")
lena_path = BASE_DIR / "lena.jpg"
if lena_path.exists():
    with open(lena_path, "rb") as f:
        lena_bytes = f.read()

    req = urllib.request.Request("http://127.0.0.1:8002/detect", data=lena_bytes, headers={"Content-Type": "image/jpeg"}, method="POST")
    with urllib.request.urlopen(req) as resp:
        det_res2 = json.loads(resp.read().decode("utf-8"))

    faces2 = det_res2.get("faces", [])
    print(f"    Detected Faces: {len(faces2)}")
    assert len(faces2) > 0, "No face detected in lena.jpg"
    f_lena = faces2[0]
    print(f"    Face #1 -> Actor: '{f_lena.get('actor')}' | Status: '{f_lena.get('status')}' | Distance: {f_lena.get('distance')}")
    assert f_lena.get("status") == "unknown", f"Expected 'unknown', got {f_lena.get('status')}"
    assert f_lena.get("distance") > 0.65, f"Expected distance > 0.65, got {f_lena.get('distance')}"
    print("    [PASS] Unregistered face classified as Unknown with distance > 0.65!")

print("\n" + "="*70)
print("ALL SESSION 8 DATA INTEGRITY VALIDATION CHECKS PASSED!")
print("="*70)
